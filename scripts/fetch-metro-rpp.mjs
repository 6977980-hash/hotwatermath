/**
 * Writes data/metro-price-parities.json: the five largest metropolitan areas of each state that has a state cost page
 * (data/state-pages.json), with BEA's Regional Price Parity (all items) for each, read from FRED.
 *
 * Largest = Census Vintage 2025 CBSA population estimate (POPESTIMATE2025), metropolitan statistical areas only, listed
 * under the first state in the area's name (so "Chicago-Naperville-Elgin, IL-IN" counts for Illinois).
 * RPP = FRED series RPPALL<CBSA code> (BEA data), latest year.
 *
 * Usage: npm run fetch:metros   (behind a proxy: NODE_USE_ENV_PROXY=1)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const CENSUS = 'https://www2.census.gov/programs-surveys/popest/datasets/2020-2025/metro/totals/cbsa-est2025-alldata.csv';
const PER_STATE = 5;
const get = async (url) => {
	const res = await fetch(url, { headers: { 'User-Agent': 'HotWaterMath-data/1.0 (+https://hotwatermath.com/methodology/)' } });
	if (!res.ok) throw new Error(`${res.status} ${url}`);
	return Buffer.from(await res.arrayBuffer()).toString('latin1');
};
const parseCsv = (text) => {
	const [head, ...lines] = text.trim().split(/\r?\n/);
	const cols = head.split(',');
	return lines.map((line) => {
		const cells = line.match(/("([^"]|"")*"|[^,]*)(,|$)/g).map((c) => c.replace(/,$/, '').replace(/^"|"$/g, '').replace(/""/g, '"'));
		return Object.fromEntries(cols.map((c, i) => [c, cells[i]]));
	});
};

const pages = JSON.parse(readFileSync(join(root, 'data/state-pages.json'), 'utf8')).statePages;
const rows = parseCsv(await get(CENSUS)).filter((r) => r.LSAD === 'Metropolitan Statistical Area');
const metrosByState = {};
const skipped = {};
for (const p of pages) {
	const mine = rows.filter((r) => r.NAME.split(', ').pop().split('-')[0] === p.code).sort((a, b) => Number(b.POPESTIMATE2025) - Number(a.POPESTIMATE2025));
	metrosByState[p.code] = [];
	for (const r of mine) {
		if (metrosByState[p.code].length >= PER_STATE) break;
		const id = `RPPALL${r.CBSA}`;
		let text;
		// A metro area first defined after BEA's last metro release has no RPP series yet: skip it and take the next one.
		try { text = await get(`https://fred.stlouisfed.org/graph/fredgraph.csv?id=${id}`); } catch (e) { if (String(e.message).startsWith('404')) { console.log(p.code, r.NAME, 'no FRED series, skipped'); (skipped[p.code] ||= []).push(r.NAME); continue; } throw e; }
		const csv = text.trim().split(/\r?\n/);
		const last = csv[csv.length - 1].split(',');
		metrosByState[p.code].push({ cbsa: r.CBSA, name: r.NAME, population: Number(r.POPESTIMATE2025), rppAllItems: Math.round(parseFloat(last[1]) * 10) / 10, year: Number(last[0].slice(0, 4)), fredSeries: id, sourceUrl: `https://fred.stlouisfed.org/series/${id}` });
		console.log(p.code, r.NAME, last.join(' '));
	}
}
const out = {
	meta: {
		source: 'U.S. Bureau of Economic Analysis (BEA), Regional Price Parities by metropolitan area, all items, read from FRED (Federal Reserve Bank of St. Louis); metro populations from U.S. Census Bureau CBSA estimates, Vintage 2025',
		sourceUrl: CENSUS,
		sourceDate: new Date().toISOString().slice(0, 10),
		notes: `The ${PER_STATE} most populous metropolitan statistical areas that have a BEA price parity series of each state with a state cost page, listed under the first state in the area's name. RPP = 100 is the U.S. average price level; state pages scale labor, permit and extras by RPP ÷ 100 exactly as the cost calculator does for states. A metro that crosses a state line has one RPP for the whole area. Generated by scripts/fetch-metro-rpp.mjs; do not edit by hand.`,
	},
	metrosByState,
	skippedNoSeries: skipped,
};
writeFileSync(join(root, 'data/metro-price-parities.json'), JSON.stringify(out, null, 2) + '\n');
console.log('wrote data/metro-price-parities.json');
